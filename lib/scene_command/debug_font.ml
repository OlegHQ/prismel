let printable_rows character =
  let character = Char.uppercase_ascii character in
  if character >= 'A' && character <= 'Z' then letter_rows character
  else if character >= '0' && character <= '9' then digit_rows character
  else symbol_rows character

let encoded_row character row =
  if row = 0 || row = height - 1 then 0x7e
  else
    let code = Char.code character in
    let bit = (code lsr (row - 1)) land 1 in
    0x42 lor (bit lsl (7 - row))

let bitmap =
  Array.init 256 (fun code ->
      let character = Char.chr code in
      if code >= 0x20 && code <= 0x7e then
        let rows = printable_rows character in
        Array.init height (fun row ->
            if row = 0 then 0 else rows.(row - 1) lsl 2)
      else Array.init height (encoded_row character))

let glyph_row character row =
  if row < 0 || row >= height then invalid_arg "Debug_font.glyph_row";
  bitmap.(Char.code character).(row)
